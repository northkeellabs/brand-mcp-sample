// Builds the DTCG 2025.10 token files with Style Dictionary v5 into, per brand:
//   build/<brand>/tokens.css        CSS custom properties, scoped to [data-brand="<brand>"]
//   build/<brand>/tokens.list.json  flat token list: path, type, resolved CSS value, description
// Source per brand = tokens/base (shared) + tokens/<brand>. Then writes src/generated/tokens.ts, the module the Worker imports.
import StyleDictionary from "style-dictionary";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { BRANDS } from "./brands.mjs";

StyleDictionary.registerFormat({
  name: "brand/token-list",
  format: ({ dictionary }) =>
    JSON.stringify(
      dictionary.allTokens.map((t) => ({
        path: t.path.join("."),
        type: t.$type ?? t.type,
        value: t.$value ?? t.value,
        ...((t.$description ?? t.description) ? { description: t.$description ?? t.description } : {}),
      })),
      null,
      2,
    ) + "\n",
});

const config = (brand) => ({
  source: ["tokens/base/**/*.tokens.json", `tokens/${brand}/**/*.tokens.json`],
  usesDtcg: true,
  log: { warnings: "error", verbosity: "default" },
  platforms: {
    css: {
      transformGroup: "css",
      buildPath: `build/${brand}/`,
      files: [{ destination: "tokens.css", format: "css/variables", options: { selector: `[data-brand="${brand}"]`, outputReferences: false } }],
    },
    list: {
      transformGroup: "css",
      buildPath: `build/${brand}/`,
      files: [{ destination: "tokens.list.json", format: "brand/token-list" }],
    },
  },
});

for (const brand of BRANDS) {
  const sd = new StyleDictionary(config(brand));
  await sd.buildAllPlatforms();
}

// ---- TypeScript module for the Worker: merged DTCG source (aliases kept), CSS text, resolved token list ----
const readJson = (p) => JSON.parse(readFileSync(p, "utf8").replace(/^﻿/, ""));
const merge = (a, b) => {
  for (const [k, v] of Object.entries(b)) {
    a[k] = v && typeof v === "object" && !Array.isArray(v) && a[k] && typeof a[k] === "object" && !("$value" in v) ? merge(a[k], v) : v;
  }
  return a;
};
const loadDtcg = (dir) => readdirSync(dir).filter((f) => f.endsWith(".tokens.json")).sort().reduce((acc, f) => merge(acc, readJson(join(dir, f))), {});

const brands = {};
for (const brand of BRANDS) {
  brands[brand] = {
    dtcg: merge(loadDtcg("tokens/base"), loadDtcg(`tokens/${brand}`)),
    css: readFileSync(`build/${brand}/tokens.css`, "utf8"),
    list: readJson(`build/${brand}/tokens.list.json`),
  };
}
mkdirSync("src/generated", { recursive: true });
writeFileSync(
  "src/generated/tokens.ts",
  `// Generated by scripts/build-tokens.mjs from tokens/**/*.tokens.json (DTCG 2025.10) with Style Dictionary v5. Do not edit.\n` +
    `export interface BrandTokens {\n  dtcg: Record<string, unknown>;\n  css: string;\n  list: { path: string; type: string; value: unknown; description?: string }[];\n}\n` +
    `export const TOKENS: Record<string, BrandTokens> = ${JSON.stringify(brands, null, 1)};\n`,
);
console.log("tokens built for", BRANDS.join(", "), "-> build/ and src/generated/tokens.ts");
